'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  platform: process.platform,
  menuAction: (action) => ipcRenderer.invoke('menu:action', action),
  isMaximized: () => ipcRenderer.invoke('window:isMaximized'),
  status: () => ipcRenderer.invoke('vault:status'),
  create: (pw, folder) => ipcRenderer.invoke('vault:create', pw, folder),
  unlock: (pw) => ipcRenderer.invoke('vault:unlock', pw),
  lock: () => ipcRenderer.invoke('vault:lock'),
  list: () => ipcRenderer.invoke('vault:list'),
  save: (entry) => ipcRenderer.invoke('vault:save', entry),
  remove: (id) => ipcRenderer.invoke('vault:delete', id),
  folders: () => ipcRenderer.invoke('vault:folders'),
  addFolder: (name) => ipcRenderer.invoke('vault:addFolder', name),
  moveToFolder: (id, folder) => ipcRenderer.invoke('vault:moveToFolder', id, folder),
  renameFolder: (from, to) => ipcRenderer.invoke('vault:renameFolder', from, to),
  deleteFolder: (name) => ipcRenderer.invoke('vault:deleteFolder', name),
  changeMaster: (current, next) => ipcRenderer.invoke('vault:changeMaster', current, next),
  generate: (opts) => ipcRenderer.invoke('generate', opts),
  copy: (text) => ipcRenderer.invoke('clipboard:copy', text),
  openUrl: (url) => ipcRenderer.invoke('openUrl', url),
  onLocked: (cb) => ipcRenderer.on('vault:locked', (_e, reason) => cb(reason)),
  onChanged: (cb) => ipcRenderer.on('vault:changed', () => cb()),
  syncProviders: () => ipcRenderer.invoke('sync:providers'),
  syncChooseFolder: () => ipcRenderer.invoke('sync:chooseFolder'),
  syncStatus: () => ipcRenderer.invoke('sync:status'),
  syncConnect: (folder) => ipcRenderer.invoke('sync:connect', folder),
  syncEnable: (folder, password, useBiometric) => ipcRenderer.invoke('sync:enable', folder, password, !!useBiometric),
  syncDisable: () => ipcRenderer.invoke('sync:disable'),
  syncUseLocal: () => ipcRenderer.invoke('sync:useLocal'),
  syncShowFolder: () => ipcRenderer.invoke('sync:showFolder'),
  onSyncStatus: (cb) => ipcRenderer.on('sync:status', (_e, s) => cb(s)),
  bioStatus: () => ipcRenderer.invoke('bio:status'),
  bioEnable: (password) => ipcRenderer.invoke('bio:enable', password),
  bioDisable: () => ipcRenderer.invoke('bio:disable'),
  bioUnlock: () => ipcRenderer.invoke('bio:unlock'),
  getPrefs: () => ipcRenderer.invoke('prefs:get'),
  setPref: (key, value) => ipcRenderer.invoke('prefs:set', key, value),
  onShown: (cb) => ipcRenderer.on('window:shown', () => cb()),
  onFullScreen: (cb) => ipcRenderer.on('window:fullscreen', (_e, on) => cb(on)),
  notifyGet: () => ipcRenderer.invoke('notify:get'),
  notifySet: (kind, on) => ipcRenderer.invoke('notify:set', kind, !!on),
  notifyScope: (scope) => ipcRenderer.invoke('notify:scope', scope),
  onNotifyChanged: (cb) => ipcRenderer.on('notify:changed', (_e, s) => cb(s)),  isWindowVisible: () => ipcRenderer.invoke('window:isVisible'),
  updateStatus: () => ipcRenderer.invoke('update:status'),
  checkForUpdates: () => ipcRenderer.invoke('update:check'),
  downloadUpdate: () => ipcRenderer.invoke('update:download'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  onUpdateStatus: (cb) => ipcRenderer.on('update:status', (_e, status) => cb(status)),
});
